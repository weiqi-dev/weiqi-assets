var TERM_NAMES = ["小寒", "大寒", "立春", "雨水", "惊蛰", "春分", "清明", "谷雨", "立夏", "小满", "芒种", "夏至", "小暑", "大暑", "立秋", "处暑", "白露", "秋分", "寒露", "霜降", "立冬", "小雪", "大雪", "冬至"];

/**
 * 传统节日业务约定（民俗，非天文事实）：农历月日 -> 节日名。
 * 逐条明说、可争议可改，来源与核验方式见同目录 README.md。
 * 除夕单独处理：取该腊月最后一天（廿九或三十），不写死「三十」。
 * 闰月不参与节日：约定只认非闰月的固定月日。
 */
var FESTIVAL_RULES = [
  { month: 1,  day: 1,  name: '春节' },
  { month: 1,  day: 15, name: '元宵' },
  { month: 5,  day: 5,  name: '端午' },
  { month: 7,  day: 7,  name: '七夕' },
  { month: 7,  day: 15, name: '中元' },
  { month: 8,  day: 15, name: '中秋' },
  { month: 9,  day: 9,  name: '重阳' },
  { month: 12, day: 8,  name: '腊八' }
];

/** 求某年 24 节气的 {name, solar} 列表；年份无事实数据时抛错，不猜测 */
function termsOfYear(y) {
  for (var i = 0; i < SOLAR_TERM_TABLE.length; i++) {
    if (SOLAR_TERM_TABLE[i][0] === y) {
      var parts = SOLAR_TERM_TABLE[i][1].split(',');
      var out = [];
      for (var k = 0; k < parts.length; k++) {
        out.push({
          name: TERM_NAMES[k],
          solar: y + '-' + parts[k].slice(0, 2) + '-' + parts[k].slice(2, 4)
        });
      }
      return out;
    }
  }
  throw new Error('年份 ' + y + ' 不在节气事实表范围（1901-2100）内');
}

/**
 * 公历 YYYY-MM-DD 落在哪个节气上；无则 null。
 * 节气事实表只覆盖 1901-2100（HKO 逐年表范围），而农历换算支持 1900-01-31 起；
 * 1900 年不在表内时返回 null，不让 toLunar 因缺少节气数据而整体失败。
 * 独立调用 solarTerms({year}) 遇到表外年份仍明确报错（那是显式查询，不静默）。
 */
function termOn(solar) {
  var y = Number(solar.slice(0, 4));
  if (y < 1901 || y > 2100) return null;
  var list = termsOfYear(y);
  for (var i = 0; i < list.length; i++) if (list[i].solar === solar) return list[i].name;
  return null;
}

/** 该农历月的天数：从朔闰表 monthList 里按 month/isLeap 找 */
function lunarMonthDays(y, month, isLeap) {
  for (var i = 0; i < LUNAR_TABLE.length; i++) {
    if (LUNAR_TABLE[i][0] === y) {
      var ms = monthList(LUNAR_TABLE[i]);
      for (var k = 0; k < ms.length; k++) {
        if (ms[k].month === month && ms[k].isLeap === isLeap) return ms[k].days;
      }
      return null;
    }
  }
  return null;
}

/** 当天传统节日；无则 null。除夕 = 腊月最后一天（该腊月无三十时以廿九为除夕） */
function festivalOn(l) {
  if (l.isLeap) return null;
  if (l.month === 12) {
    var md = lunarMonthDays(l.year, 12, false);
    if (md !== null && l.day === md) return '除夕';
  }
  for (var i = 0; i < FESTIVAL_RULES.length; i++) {
    var r = FESTIVAL_RULES[i];
    if (l.month === r.month && l.day === r.day) return r.name;
  }
  return null;
}

var BASE_UTC = Date.UTC(1900, 0, 31);
var DAY_MS = 86400000;

function pad2(n) { return (n < 10 ? '0' : '') + n; }

/** 严格解析 YYYY-MM-DD；用 UTC 回显比对，拒绝 2026-02-30 这类被静默归一化的日期 */
function parseDate(s) {
  if (typeof s !== 'string') throw new Error('日期必须是 YYYY-MM-DD 字符串');
  var m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(s);
  if (!m) throw new Error('日期格式必须是 YYYY-MM-DD：' + s);
  var y = Number(m[1]), mo = Number(m[2]), d = Number(m[3]);
  if (mo < 1 || mo > 12 || d < 1 || d > 31) throw new Error('日期超出范围：' + s);
  var t = Date.UTC(y, mo - 1, d);
  var back = new Date(t);
  if (back.getUTCFullYear() !== y || back.getUTCMonth() !== mo - 1 || back.getUTCDate() !== d) {
    throw new Error('不存在的日期：' + s);
  }
  return { y: y, m: mo, d: d, t: t };
}

function isoOf(t) {
  var dt = new Date(t);
  return String(dt.getUTCFullYear()) + '-' + pad2(dt.getUTCMonth() + 1) + '-' + pad2(dt.getUTCDate());
}

/** 该农历年总天数：12 个月各 29/30 天，加闰月天数。全部由表行推导，无外部常数 */
function yearDays(row) {
  var sum = 0;
  for (var i = 0; i < 12; i++) sum += row[2].charAt(i) === '1' ? 30 : 29;
  if (row[1] > 0) sum += row[3] ? 30 : 29;
  return sum;
}

/** 年内月份序列：正月..腊月，闰月插在同名月之后 */
function monthList(row) {
  var arr = [];
  var leap = row[1];
  for (var m = 1; m <= 12; m++) {
    arr.push({ month: m, isLeap: false, days: row[2].charAt(m - 1) === '1' ? 30 : 29 });
    if (m === leap) arr.push({ month: m, isLeap: true, days: row[3] ? 30 : 29 });
  }
  return arr;
}

var MONTH_CN = ['正月','二月','三月','四月','五月','六月','七月','八月','九月','十月','冬月','腊月'];
var DAY_CN_NUM = ['','一','二','三','四','五','六','七','八','九','十'];

function dayText(d) {
  if (d === 10) return '初十';
  if (d === 20) return '二十';
  if (d === 30) return '三十';
  if (d < 10) return '初' + DAY_CN_NUM[d];
  if (d < 20) return '十' + DAY_CN_NUM[d - 10];
  if (d < 30) return '廿' + DAY_CN_NUM[d - 20];
  return String(d);
}

/** 公历某日 → 农历年月日。offset 逐层扣减年天数、月天数，定位到具体月日 */
function solarToLunar(y, m, d) {
  var target = Date.UTC(y, m - 1, d);
  var offset = Math.round((target - BASE_UTC) / DAY_MS);
  if (offset < 0) throw new Error('日期早于支持范围起点 1900-01-31');
  var i = 0;
  while (i < LUNAR_TABLE.length) {
    var yd = yearDays(LUNAR_TABLE[i]);
    if (offset < yd) break;
    offset -= yd;
    i++;
  }
  if (i >= LUNAR_TABLE.length) throw new Error('日期超出数据表范围（1900-01-31 起，至 2100 农历年末）');
  var row = LUNAR_TABLE[i];
  var months = monthList(row);
  var k = 0;
  while (k < months.length) {
    if (offset < months[k].days) break;
    offset -= months[k].days;
    k++;
  }
  var hit = months[k];
  return {
    year: row[0], month: hit.month, day: offset + 1, isLeap: hit.isLeap,
    text: (hit.isLeap ? '闰' : '') + MONTH_CN[hit.month - 1] + dayText(offset + 1)
  };
}

/**
 * 对外的唯一方法。
 *   { date: '2026-11-17' }              单日（等价于 from=to）
 *   { from: '2026-11-17', to: '2026-11-19' }  日期范围
 *   { year: 2026, month: 11, day: 17 }  数字形式单日
 * 一律返回 { from, to, count, days[] }，单日即 count=1 的数组，形状稳定。
 * 范围长度不设人为上限：逐日次数由起止日期差推导，超长输出由宿主既有输出体积约束回喂。
 */
function toLunar(spec) {
  if (!spec || typeof spec !== 'object') throw new Error('参数必须是对象');
  var fromStr, toStr;
  if (typeof spec.date === 'string') {
    fromStr = spec.date; toStr = spec.date;
  } else if (spec.year !== undefined && spec.month !== undefined && spec.day !== undefined) {
    fromStr = String(spec.year) + '-' + pad2(spec.month) + '-' + pad2(spec.day);
    toStr = fromStr;
  } else if (typeof spec.from === 'string' && typeof spec.to === 'string') {
    fromStr = spec.from; toStr = spec.to;
  } else {
    throw new Error('需要 {date} 或 {year,month,day} 或 {from,to}');
  }
  var a = parseDate(fromStr), b = parseDate(toStr);
  var span = Math.round((b.t - a.t) / DAY_MS);
  if (span < 0) throw new Error('起始日期不能晚于结束日期');
  var days = [];
  for (var k = 0; k <= span; k++) {
    var t = a.t + k * DAY_MS;
    var dt = new Date(t);
    var iso = isoOf(t);
    var l = solarToLunar(dt.getUTCFullYear(), dt.getUTCMonth() + 1, dt.getUTCDate());
    days.push({
      solar: iso,
      lunar: { year: l.year, month: l.month, day: l.day, isLeap: l.isLeap },
      lunarText: l.text,
      solarTerm: termOn(iso),
      festival: festivalOn(l)
    });
  }
  return { from: fromStr, to: toStr, count: days.length, days: days };
}

